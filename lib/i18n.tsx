type LocaleContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (message: string) => string
}

const LocaleContext = createContext<LocaleContextValue | null>(null)

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && LOCALES.includes(value as Locale)
}

export function LocaleProvider({ children, initialLocale = DEFAULT_LOCALE }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale] = useState<Locale>(initialLocale)

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const setLocale = useCallback((nextLocale: Locale) => {
    if (!isLocale(nextLocale)) return
    if (nextLocale === locale) return
    document.cookie = `${LOCALE_COOKIE}=${encodeURIComponent(nextLocale)}; Path=/; Max-Age=31536000; SameSite=Lax`
    window.localStorage.setItem(LOCALE_COOKIE, nextLocale)
    window.location.reload()
  }, [locale])

  const t = useCallback((message: string) => messages[locale][message] ?? message, [locale])
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  const value = useContext(LocaleContext)
  if (!value) throw new Error("useLocale must be used within LocaleProvider")
  return value
}

export function LocaleSwitcher() {
  const { locale, setLocale } = useLocale()
  return (
    <label className="fixed bottom-4 right-4 z-[100] flex items-center gap-2 rounded-lg border border-gray-200 bg-white/95 px-3 py-2 text-sm shadow-lg backdrop-blur dark:border-gray-700 dark:bg-gray-900/95">
      <span className="text-gray-600 dark:text-gray-300">{messages[locale]["Язык"] ?? "Язык"}</span>
      <select
        aria-label="Язык интерфейса"
        className="bg-transparent font-medium text-gray-900 outline-none dark:text-white"
        value={locale}
        onChange={(event) => setLocale(event.target.value as Locale)}
      >
        <option value="uz-Latn">O‘zbekcha</option>
        <option value="uz-Cyrl">Ўзбекча</option>
        <option value="ru">Русский</option>
      </select>
    </label>
  )
}
